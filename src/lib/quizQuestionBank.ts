function generateDynamicMathQuestions(chapterTitle: string, count: number): RawQA[] {
  const dynamicList: RawQA[] = [];
  for (let i = 0; i < count; i++) {
    const a = Math.floor(Math.random() * 9) + 3;
    const b = Math.floor(Math.random() * 9) + 2;
    const xVal = Math.floor(Math.random() * 7) + 2;
    const type = i % 4;
    if (type === 0) {
      const c = a * xVal + b;
      const opts = [String(xVal), String(xVal + 2), String(Math.max(1, xVal - 1)), String(xVal + 4)];
      dynamicList.push({
        q: `[${chapterTitle}] यदि समीकरण ${a}x + ${b} = ${c} हो, तो x का मान क्या होगा?`,
        options: [opts[0], opts[1], opts[2], opts[3]],
        ans: 0,
        exp: `${a}x = ${c} - ${b} = ${c - b} ⇒ x = ${c - b}/${a} = ${xVal}।`,
      });
    } else if (type === 1) {
      const d = b;
      const n = Math.floor(Math.random() * 6) + 5;
      const nth = a + (n - 1) * d;
      dynamicList.push({
        q: `[${chapterTitle}] समांतर श्रेढ़ी ${a}, ${a + d}, ${a + 2 * d}, ... का ${n}वाँ पद क्या होगा?`,
        options: [String(nth), String(nth + d), String(nth - d), String(nth + 2 * d)],
        ans: 0,
        exp: `सूत्र an = a + (n - 1)d = ${a} + (${n} - 1)×${d} = ${nth}।`,
      });
    } else if (type === 2) {
      const side1 = 3 * xVal;
      const side2 = 4 * xVal;
      const hyp = 5 * xVal;
      dynamicList.push({
        q: `[${chapterTitle}] एक समकोण त्रिभुज का आधार ${side1} cm और लंब ${side2} cm है, तो कर्ण (Hypotenuse) की लंबाई क्या होगी?`,
        options: [`${hyp} cm`, `${hyp + 2} cm`, `${side1 + side2} cm`, `${hyp - 3} cm`],
        ans: 0,
        exp: `पाइथागोरस प्रमेय से: कर्ण = √(${side1}² + ${side2}²) = ${hyp} cm।`,
      });
    } else {
      const pVal = a * xVal * xVal + b * xVal;
      dynamicList.push({
        q: `[${chapterTitle}] यदि बहुपद P(x) = ${a}x² + ${b}x हो, तो x = ${xVal} पर P(${xVal}) का मान ज्ञात कीजिए:`,
        options: [String(pVal), String(pVal + a), String(pVal - b), String(pVal + 5)],
        ans: 0,
        exp: `P(${xVal}) = ${a}(${xVal})² + ${b}(${xVal}) = ${a * xVal * xVal} + ${b * xVal} = ${pVal}।`,
      });
    }
  }
  return dynamicList;
}

function generateDynamicScienceQuestions(chapterTitle: string, count: number): RawQA[] {
  const dynamicList: RawQA[] = [];
  for (let i = 0; i < count; i++) {
    const m = Math.floor(Math.random() * 12) + 2;
    const acc = Math.floor(Math.random() * 8) + 2;
    const type = i % 3;
    if (type === 0) {
      const force = m * acc;
      dynamicList.push({
        q: `[${chapterTitle}] यदि ${m} kg द्रव्यमान की वस्तु में ${acc} m/s² का त्वरण उत्पन्न होता है, तो लगने वाला बल (F = ma) कितना होगा?`,
        options: [`${force} N`, `${force + m} N`, `${m + acc} N`, `${Math.max(1, force - acc)} N`],
        ans: 0,
        exp: `न्यूटन के द्वितीय नियम से F = m × a = ${m} × ${acc} = ${force} न्यूटन (N)।`,
      });
    } else if (type === 1) {
      const current = m;
      const resistance = acc;
      const voltage = current * resistance;
      dynamicList.push({
        q: `[${chapterTitle}] किसी चालक का प्रतिरोध ${resistance} Ω है और उसमें ${current} A की विद्युत धारा प्रवाहित हो रही है। विभवांतर (V = IR) कितना होगा?`,
        options: [`${voltage} V`, `${voltage + 5} V`, `${current + resistance} V`, `${Math.max(2, voltage - 4)} V`],
        ans: 0,
        exp: `ओम के नियम से V = I × R = ${current} × ${resistance} = ${voltage} वोल्ट (V)।`,
      });
    } else {
      const work = m * 10 * acc;
      dynamicList.push({
        q: `[${chapterTitle}] ${m * 10} N के बल द्वारा किसी वस्तु को बल की दिशा में ${acc} मीटर विस्थापित करने पर किया गया कार्य (W = F × d) होगा:`,
        options: [`${work} जूल (J)`, `${work + 20} जूल (J)`, `${m * 10 + acc} जूल (J)`, `${work / 2} जूल (J)`],
        ans: 0,
        exp: `किया गया कार्य W = बल × विस्थापन = ${m * 10} × ${acc} = ${work} जूल (J)।`,
      });
    }
  }
  return dynamicList;
}

function shuffleOptions(raw: RawQA): QuizQuestion {
  const indexed = raw.options.map((text, idx) => ({ text, isCorrect: idx === raw.ans }));
  for (let i = indexed.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [indexed[i], indexed[j]] = [indexed[j], indexed[i]];
  }
  const correctIndex = indexed.findIndex((item) => item.isCorrect);
  return {
    questionText: raw.q,
    options: [indexed[0].text, indexed[1].text, indexed[2].text, indexed[3].text],
    correctIndex: correctIndex >= 0 ? correctIndex : 0,
    explanation: raw.exp,
  };
}

export function buildChapterQuizSession(
  classLevel: '9' | '10' | '11' | '12',
  subjectId: string,
  chapterTitle: string,
  desiredCount: number = 12
): QuizQuestion[] {
  const targetCount = Math.max(10, Math.min(15, desiredCount));
  let basePool: RawQA[] = [];

  if (SUBJECT_POOLS[subjectId]) {
    basePool = [...SUBJECT_POOLS[subjectId]];
  } else if (ARTS_POOLS[subjectId]) {
    basePool = [...ARTS_POOLS[subjectId], ...SUBJECT_POOLS['Social Science']];
  } else {
    basePool = [...SUBJECT_POOLS.Science, ...SUBJECT_POOLS['Social Science']];
  }

  // Add varying parametric numerical/conceptual questions so every daily practice session has fresh variations
  if (subjectId === 'Mathematics') {
    basePool = [...generateDynamicMathQuestions(chapterTitle, 6), ...basePool];
  } else if (subjectId === 'Science' || subjectId === 'Physics' || subjectId === 'Chemistry') {
    basePool = [...generateDynamicScienceQuestions(chapterTitle, 5), ...basePool];
  }

  // Shuffle the entire pool
  const shuffledPool = [...basePool];
  for (let i = shuffledPool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffledPool[i], shuffledPool[j]] = [shuffledPool[j], shuffledPool[i]];
  }

  const selected = shuffledPool.slice(0, targetCount);
  return selected.map((item) => {
    const hasChapterTag = item.q.startsWith('[');
    const taggedItem: RawQA = {
      ...item,
      q: hasChapterTag ? item.q : `[कक्षा ${classLevel}वीं • ${chapterTitle}] ${item.q}`,
    };
    return shuffleOptions(taggedItem);
  });
}
